// Picks checkpoint positions (20/40/60/80%) for every level from the solver's perfect-run route
// and writes packages/shared/src/levels/checkpoints.ts.
// Usage: npx tsx tools/gen-checkpoints.ts [beam, default 250]
// Each checkpoint is the first spot on the route, at or after its progress mark and within 7%
// of it, where the blob stands on a safe flat pad (padIsSafe). Run it again whenever a level changes.
import { writeFileSync } from 'node:fs';
import { CHECKPOINT_STEP, LEVELS, PHYS, createBody, createDynamics, levelHash, padIsSafe, progressOf, stepBody, type Body, type Control, type Dynamics, type Level } from '../packages/shared/src/index';
import { HOLD_STEPS, solve } from './lib/solver';

const beam = Number(process.argv[2] ?? 250);
const WINDOW = 0.07;

function routeOf(level: Level): Body[] {
  const samples: Body[] = [];
  let b = createBody(level);
  let dyn: Dynamics = createDynamics();
  for (const z of level.zones) {
    const r = solve(level, Math.min(z.endX, level.goalX - 0.5), beam, 600, { b, dyn });
    if (!r.ok) throw new Error(`level ${level.id}: solver stuck in ${z.name} at x=${r.maxX.toFixed(1)}`);
    const bb = { ...b }, dd: Dynamics = { ...dyn, crumbles: new Map(dyn.crumbles) };
    for (const c of r.plan as Control[]) for (let i = 0; i < HOLD_STEPS; i++) { stepBody(bb, c, level, dd); samples.push({ ...bb }); }
    b = bb; dyn = dd;
  }
  return samples;
}

const out: Record<number, { hash: string; points: [number, number][] }> = {};
for (const level of LEVELS) {
  const route = routeOf(level);
  const points: [number, number][] = [];
  for (let k = 1; k <= 4; k++) {
    const target = k * CHECKPOINT_STEP;
    let found: [number, number] | null = null;
    for (const s of route) {
      const p = progressOf(level, s.x);
      if (p < target) continue;
      if (p > target + WINDOW) break;
      if (!s.grounded) continue;
      const x = Math.floor(s.x) + 0.5;
      const y = Math.round(s.y + PHYS.halfH) - PHYS.halfH;
      if (padIsSafe(level, x, y)) { found = [x, y]; break; }
    }
    if (!found) throw new Error(`level ${level.id}: no safe pad for the ${Math.round(target * 100)}% checkpoint (window ${target}..${target + WINDOW})`);
    points.push(found);
    console.log(`level ${level.id} checkpoint ${k}: x=${found[0]} y=${found[1].toFixed(2)} (${(progressOf(level, found[0]) * 100).toFixed(1)}%)`);
  }
  out[level.id] = { hash: levelHash(level), points };
}
const body = Object.entries(out).map(([id, d]) => `  ${id}: { hash: '${d.hash}', points: ${JSON.stringify(d.points)} },`).join('\n');
writeFileSync(new URL('../packages/shared/src/levels/checkpoints.ts', import.meta.url),
  `// Generated by tools/gen-checkpoints.ts: do not edit by hand.\nexport const CHECKPOINT_DATA: Record<number, { hash: string; points: [number, number][] }> = {\n${body}\n};\n`);
console.log('written');
